export function getLeaderboardFromStudents(students: StudentProfile[]): LeaderboardEntry[] {
  return [...students]
    .sort((a, b) => b.xp - a.xp)
    .map((student, idx) => ({
      id: student.id,
      name: student.name,
      avatar: student.avatar,
      grade: student.grade,
      xp: student.xp,
      quizzesCompleted: student.quizzesCompleted,
      accuracy: student.overallAccuracy,
      rank: idx + 1,
      badges: getBadgesForStudent(student),
      isCurrentUser: student.id === 'std_1',
    }));
}

function getBadgesForStudent(student: StudentProfile): string[] {
  const badges: string[] = [];
  if (student.xp >= 2500) badges.push('Grandmaster Algebraist');
  else if (student.xp >= 2000) badges.push('Equation Ace');
  else badges.push('Rising Star');

  if (student.streakDays >= 7) badges.push('🔥 7-Day Streak');
  if (student.overallAccuracy >= 90) badges.push('🎯 90%+ Accuracy');
  if (student.quizzesCompleted >= 20) badges.push('⚡ Quiz Champion');
  return badges;
}
